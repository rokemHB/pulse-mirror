"""Build the static GitHub Pages demo: the real dashboard + JSON snapshots of the API.

The JSON files are produced by the same endpoint functions the server uses, so
the demo can't drift from the real API shapes. The dashboard's static adapter
(``web/js/api.js``) serves reads from these files and keeps edits in localStorage.
"""

from __future__ import annotations

import json
import shutil
import tempfile
from datetime import date
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from pulse_mirror import __version__
from pulse_mirror.api import schemas as s
from pulse_mirror.api.app import WEB_DIR
from pulse_mirror.api.auth import Principal
from pulse_mirror.api.v1 import core, events, wellbeing
from pulse_mirror.db import connect, migrate
from pulse_mirror.demo.generator import generate

_DEMO = Principal("session")


def _dump(value: Any) -> Any:
    if isinstance(value, BaseModel):
        return value.model_dump(mode="json")
    if isinstance(value, list):
        return [_dump(v) for v in value]
    return value


def build_pages(out_dir: Path, end: date, days: int = 900) -> Path:
    out_dir = out_dir.resolve()
    if out_dir.exists():
        shutil.rmtree(out_dir)
    shutil.copytree(WEB_DIR, out_dir)

    with tempfile.TemporaryDirectory() as tmp:
        conn = connect(Path(tmp) / "demo.db")
        migrate(conn)
        generate(conn, end, days)
        first, last = conn.execute("SELECT MIN(date), MAX(date) FROM daily_metrics").fetchone()
        last_ok = conn.execute(
            "SELECT * FROM sync_runs WHERE status = 'ok' ORDER BY id DESC LIMIT 1"
        ).fetchone()
        data: dict[str, Any] = {
            "status": s.Status(
                version=__version__,
                demo=True,
                timezone="Europe/Berlin",
                sources=[
                    s.SourceStatus(
                        source="garmin",
                        last_success_at=f"{end.isoformat()}T07:02:00Z",
                        last_run=s.SyncRun(
                            **dict(last_ok)
                            | {
                                "started_at": f"{end.isoformat()}T07:00:00Z",
                                "finished_at": f"{end.isoformat()}T07:02:00Z",
                            }
                        ),
                        syncing=False,
                        cooldown_until=None,
                    )
                ],
                backfill=None,
                data_range=(first, last),
            ),
            "metrics": core.metric_types(conn, _DEMO),
            "daily": core.daily_metrics(conn, _DEMO, None, None, None, None),
            "activities": core.activities(conn, _DEMO, None, None, None, 5000),
            "event-categories": events.list_categories(conn, _DEMO),
            "events": events.list_events(conn, _DEMO, None, None, None),
            "scales": wellbeing.list_scales(conn, _DEMO, False),
            "ratings": wellbeing.list_ratings(conn, _DEMO, None, None, None, None, False),
        }
        conn.close()

    target = out_dir / "demo-data"
    target.mkdir()
    for name, value in data.items():
        (target / f"{name}.json").write_text(json.dumps(_dump(value), separators=(",", ":")))
    (out_dir / "config.js").write_text(
        "// Generated by `pulse-mirror demo build-pages`.\n"
        'window.PULSE_CONFIG = { mode: "static", dataUrl: "demo-data/" };\n'
    )
    (out_dir / ".nojekyll").write_text("")
    return out_dir
